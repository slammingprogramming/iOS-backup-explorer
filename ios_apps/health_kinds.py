"""Health's kind numbers, for databases that do not name them.

Every sample in the Health database has a number for its kind
(``samples.data_type``): 7 for steps, 5 for heart rate... Apple does not
publish the numbers. From iOS 13 on, the database names them itself (the
shared summaries, see ``health.kind_names``) and that is always what is used.

An older database (iOS 12 and before) has no such names. For it, this table
supplies them. It holds the numbers that the databases of two real backups,
**iOS 16.7 and iOS 26.6, both name, and name identically**: 172 numbers with a
name in the iOS 16.7 database, every one of which the iOS 26.6 database names
the same way (none differed), so the numbers have not been renumbered between
those versions. A number that is not in the table stays "Type N".

Checked on an iOS 12.4 database: its five kinds (2 height, 3 body mass, 7 step
count, 8 walking distance, 63 sleep) are in the table, and the data fits: the
height was recorded in centimetres (a unit string in the database), sleep is a
category (every sleep sample has a category value), steps and distance are
measurements taken at the same moments. The table was made from the two
databases themselves; it is not copied from any other project.
"""

